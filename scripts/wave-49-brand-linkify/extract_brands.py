"""Extract all unique brand display values from city-service-content.ts
+ check which have matching /brands/{slug}.astro pillar files."""
import re
import json
from pathlib import Path

ROOT = Path(r"C:\Users\Roman\WebstormProjects\sdar-v2")
SOURCE = ROOT / "src" / "data" / "city-service-content.ts"
BRANDS_DIR = ROOT / "src" / "pages" / "brands"

content = SOURCE.read_text(encoding="utf-8")

brand_pool_pattern = re.compile(r"brandPool\w+:\s*\[([^\]]+)\]", re.MULTILINE)
all_brands = set()
for match in brand_pool_pattern.finditer(content):
    array_content = match.group(1)
    for s in re.findall(r"['\"]([^'\"]+)['\"]", array_content):
        all_brands.add(s.strip())

print(f"Unique brand display values: {len(all_brands)}")

pillar_files = set()
for f in BRANDS_DIR.glob("*.astro"):
    name = f.stem
    if name != "index" and not name.endswith("-repair"):
        pillar_files.add(name)

print(f"Existing pillar files: {len(pillar_files)}")


def display_to_slug(display):
    """Convert 'Sub-Zero' -> 'sub-zero', 'GE Cafe' -> 'ge-cafe', 'Fisher & Paykel' -> 'fisher-paykel'."""
    s = display.lower()
    s = s.replace("é", "e").replace("è", "e").replace("ñ", "n")
    s = s.replace(" & ", " ").replace("&", "")
    s = re.sub(r"\s+", "-", s.strip())
    s = re.sub(r"[^a-z0-9-]", "", s)
    s = re.sub(r"-+", "-", s).strip("-")
    return s


mapping = {}
unmapped = []
for brand in sorted(all_brands):
    slug = display_to_slug(brand)
    attempts = [slug]
    # Fallback 1: remove ALL hyphens (Jenn-Air -> jennair)
    attempts.append(slug.replace("-", ""))
    # Fallback 2: parenthetical stripped (Cove (Sub-Zero family) -> cove)
    base_slug = display_to_slug(brand.split("(")[0].strip())
    attempts.append(base_slug)

    matched = None
    for attempt in attempts:
        if attempt in pillar_files:
            matched = attempt
            break

    if matched:
        mapping[brand] = matched
    else:
        unmapped.append((brand, slug))

print(f"\nMapped brands: {len(mapping)}")
print(f"Unmapped brands (will render plain <li>): {len(unmapped)}")

if unmapped:
    print("\nUnmapped list:")
    for b, attempted_slug in unmapped:
        print(f"  '{b}' (tried slug: {attempted_slug})")

ts_lines = [
    "// Auto-generated by scripts/wave-49-brand-linkify/extract_brands.py",
    "// DO NOT EDIT MANUALLY. Re-run script if brand pool data changes.",
    "// Maps brand display names (as used in city-service-content.ts brandPool arrays)",
    "// to /brands/{slug}/ pillar URL slugs.",
    "// Brands without a pillar are omitted - caller should fallback to plain text.",
    "",
    "export const BRAND_PILLAR_MAP: Record<string, string> = {",
]
for brand, slug in sorted(mapping.items()):
    escaped = brand.replace("'", "\\'")
    ts_lines.append(f"  '{escaped}': '{slug}',")
ts_lines.append("};")
ts_lines.append("")
ts_lines.append("export function getBrandPillarSlug(display: string): string | null {")
ts_lines.append("  return BRAND_PILLAR_MAP[display] ?? null;")
ts_lines.append("}")

out_ts = ROOT / "src" / "data" / "brand-pillar-map.ts"
out_ts.write_text("\n".join(ts_lines), encoding="utf-8")
print(f"\nWrote: {out_ts}")

out_json = ROOT / "audit-output" / "wave-49-brand-mapping.json"
out_json.write_text(json.dumps({
    "mapped": mapping,
    "unmapped": [{"display": b, "attempted_slug": s} for b, s in unmapped],
    "total_brands": len(all_brands),
    "mapped_count": len(mapping),
    "unmapped_count": len(unmapped),
}, indent=2, ensure_ascii=False), encoding="utf-8")
